def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="dgac", description="Data Governance as Code: the standard's tool.")
    parser.add_argument("--version", action="version", version=f"dgac {__version__}")
    parser.add_argument("--hub", type=Path, help="folder holding governance/hub.yml (default: found from here upwards)")
    parser.add_argument("--domain", type=Path, action="append", dest="domains",
                        help="a domain folder (default: every domains/*/ of the hub)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate", help="check every governance file against its schema")
    g = sub.add_parser("generate", help="rewrite CODEOWNERS, dbt groups, selectors and dbt semantic config")
    g.add_argument("--check", action="store_true", help="fail if a generated file is out of date (CI)")
    b = sub.add_parser("build", help="run dbt for every domain, producers first, one product at a time")
    b.add_argument("--parse-only", action="store_true",
                   help="only parse the dbt projects, with a throwaway profile: no warehouse, no secret (CI)")
    b.add_argument("--dbt", help="the dbt executable (default: the one installed with dgac, else on the PATH)")
    sub.add_parser("assemble", help="write each product's assembled Ossie model to build/semantic/")
    sub.add_parser("manifest", help="write build/<domain>/governance-manifest.json")
    it = sub.add_parser("init", help="remove the Lumen Retail example and set the hub up for your company")
    it.add_argument("--organisation", required=True, help="your company's name")
    it.add_argument("--central-team", required=True, help="GitHub team of the central data governance team")
    it.add_argument("--force", action="store_true", help="remove the example even if the repository was changed")
    it.add_argument("--keep-tool", action="store_true",
                    help="keep the tool's source here instead of installing a pinned release (CI without GitHub access)")
    nd = sub.add_parser("new-domain", help="create a domain folder, or a domain repository with --repo")
    nd.add_argument("domain")
    nd.add_argument("--team", required=True, help="GitHub team of the domain, e.g. @org/sales-data")

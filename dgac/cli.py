#!/usr/bin/env python3
"""Data Governance as Code: the standard's tool.

    dgac validate                 check every governance file against its schema
    dgac generate [--check]       rewrite CODEOWNERS, dbt groups, selectors, dbt semantic config
    dgac build [--parse-only]     run dbt for every domain (producers first), one product at a time;
                                  --parse-only checks the projects without a warehouse (CI)
    dgac assemble                 write each product's assembled Ossie model to build/semantic/
    dgac manifest                 write build/<domain>/governance-manifest.json
    dgac init --organisation NAME --central-team @org/team    remove the example, set the hub up
    dgac new-domain <domain> --team @org/team [--repo PATH]
    dgac adopt <domain> --team @org/team [--path DIR]     set the standard up on an existing dbt project
    dgac new-product <domain> <product> --team @org/team --owner EMAIL --steward EMAIL
    dgac new-interface <domain> <product> <interface>

Run it anywhere inside the repository: it finds the hub (governance/hub.yml) in the current
folder or a parent. In a repository per domain, point it to a copy of the hub:
    dgac --hub ../hub --domain . validate

V1 of the standard checks the shape of files (schemas), not the rules of RULES.md: those are
reviewed by hand. The semantic assembly refuses what the standard forbids (GOV-315 to GOV-318),
because it cannot produce a valid model otherwise.
"""

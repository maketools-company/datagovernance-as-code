#!/usr/bin/env python3
"""Data Governance as Code: the standard's tool.

    python tools/dgac.py validate                 check every governance file against its schema
    python tools/dgac.py generate [--check]       rewrite CODEOWNERS, dbt groups, selectors, dbt semantic config
    python tools/dgac.py build                    run dbt for every domain (producers first), one product at a time
    python tools/dgac.py assemble                 write each product's assembled Ossie model to build/semantic/
    python tools/dgac.py manifest                 write build/<domain>/governance-manifest.json
    python tools/dgac.py new-domain <domain> --team @org/team [--repo PATH]
    python tools/dgac.py new-product <domain> <product> --team @org/team --owner EMAIL --steward EMAIL
    python tools/dgac.py new-interface <domain> <product> <interface>

In a repository per domain, point the tool to the hub and to the domain:
    python hub/tools/dgac.py --hub hub --domain . validate

V1 of the standard checks the shape of files (schemas), not the rules of RULES.md: those are
reviewed by hand. The semantic assembly refuses what the standard forbids (GOV-315 to GOV-318),
because it cannot produce a valid model otherwise.
"""

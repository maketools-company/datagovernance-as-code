# ---------------------------------------------------------------- files

class _Loader(yaml.SafeLoader):
    """Safe loader that keeps dates as strings, as JSON Schema expects."""


_Loader.yaml_implicit_resolvers = {
    k: [(tag, rx) for tag, rx in v if tag != "tag:yaml.org,2002:timestamp"]
    for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()
}


def load_yaml(path: Path):
    with path.open(encoding="utf-8") as f:
        return yaml.load(f, Loader=_Loader) or {}


def dump_yaml(data) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


class Problems:
    def __init__(self):
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, where, message):
        self.errors.append(f"{where}: {message}")

    def warn(self, where, message):
        self.warnings.append(f"{where}: {message}")

    def report(self) -> int:
        for w in self.warnings:
            print(f"warning  {w}")
        for e in self.errors:
            print(f"error    {e}")
        return 1 if self.errors else 0


# ---------------------------------------------------------------- model of the repository

@dataclass
class Interface:
    name: str
    version: int
    sql: Path
    contract_path: Path
    contract: dict | None = None


@dataclass
class Product:
    id: str
    path: Path
    card: dict | None = None
    extension: dict | None = None
    interfaces: list[Interface] = field(default_factory=list)

    def card_property(self, name):
        for p in (self.card or {}).get("customProperties", []) or []:
            if p.get("property") == name:
                return p.get("value")
        return None

    def member(self, role):
        for m in ((self.card or {}).get("team") or {}).get("members", []) or []:
            if m.get("role") == role:
                return m.get("username")
        return None

    @property
    def tech_owner(self):
        return ((self.card or {}).get("team") or {}).get("name")


@dataclass
class External:
    model: str            # dbt model name in the consumer zone
    path: Path
    group: str | None     # data product that uses it
    domain: str           # producing domain
    interface: str
    version: int | None


@dataclass
class Domain:
    name: str
    path: Path
    gov: dict
    products: list[Product] = field(default_factory=list)
    externals: list[External] = field(default_factory=list)

    @property
    def repo_root(self) -> Path:
        """The git repository holding this domain: the monorepo, or the domain itself."""
        if self.path.parent.name == "domains" and (self.path.parent.parent / "governance" / "hub.yml").exists():
            return self.path.parent.parent
        return self.path

    def product(self, pid):
        return next((p for p in self.products if p.id == pid), None)


class Repo:
    def __init__(self, hub_root: Path, domain_dirs: list[Path] | None = None):
        self.hub_root = hub_root
        self.gov_dir = hub_root / "governance"
        self.schemas = TOOL_ROOT / "schemas" if not (hub_root / "schemas").exists() else hub_root / "schemas"
        self.hub = load_yaml(self.gov_dir / "hub.yml")
        self.levels = [lvl["id"] for lvl in load_yaml(self.gov_dir / "classification.yaml").get("levels", [])]
        self.ranks = {lvl["id"]: lvl.get("rank", 0) for lvl in load_yaml(self.gov_dir / "classification.yaml").get("levels", [])}
        if domain_dirs is None:
            domain_dirs = sorted(p.parent for p in (hub_root / "domains").glob("*/governance.yml"))
        self.domains = [self._load_domain(d) for d in domain_dirs]

    # loading ---------------------------------------------------------------
    def _load_domain(self, path: Path) -> Domain:
        path = path.resolve()
        gov = load_yaml(path / "governance.yml") if (path / "governance.yml").exists() else {}
        domain = Domain(gov.get("domain", path.name), path, gov)
        for folder in sorted(p for p in (path / "dataproducts").glob("*") if p.is_dir()):
            product = Product(folder.name, folder)
            if (folder / CARD).exists():
                product.card = load_yaml(folder / CARD)
            ext = folder / f"{folder.name}.ossie.yaml"
            if ext.exists():
                product.extension = load_yaml(ext)
            for sql in sorted((folder / "public").glob("*_v*.sql")):
                m = re.match(r"^(.+)_v(\d+)$", sql.stem)
                if not m:
                    continue
                contract = folder / "public" / f"{sql.stem}.odcs.yaml"
                iface = Interface(m.group(1), int(m.group(2)), sql, contract)
                if contract.exists():
                    iface.contract = load_yaml(contract)
                product.interfaces.append(iface)
            domain.products.append(product)
        groups = {}
        for yml in (path / "external").rglob("*.yml"):
            for model in (load_yaml(yml).get("models") or []):
                groups[model.get("name")] = (model.get("config") or {}).get("group") or model.get("group")
        for sql in sorted((path / "external").rglob("*.sql")):
            for dom, iface, version in CROSS_REF.findall(sql.read_text(encoding="utf-8")):
                domain.externals.append(External(sql.stem, sql, groups.get(sql.stem), dom, iface,
                                                 int(version) if version else None))
        return domain

    def domain(self, name) -> Domain | None:
        return next((d for d in self.domains if d.name == name), None)

    def common_model(self) -> dict:
        return load_yaml(self.hub_root / self.hub["common_semantic_model"]["path"])

    def dbt_manifest(self, domain: Domain) -> dict | None:
        path = domain.path / "target" / "manifest.json"
        return json.loads(path.read_text()) if path.exists() else None

    def build_dir(self, domain: Domain) -> Path:
        return domain.repo_root / "build"

    def order(self) -> list[Domain]:
        """Domains with producers before the consumers that read them."""
        done, out = set(), []

        def visit(d, stack=()):
            if d.name in done or d.name in stack:
                return
            for e in d.externals:
                up = self.domain(e.domain)
                if up:
                    visit(up, stack + (d.name,))
            done.add(d.name)
            out.append(d)

        for d in self.domains:
            visit(d)
        return out


def rel(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path)


# ---------------------------------------------------------------- validate

class Schemas:
    def __init__(self, folder: Path):
        self.folder = folder
        self._cache = {}

    def check(self, problems: Problems, where: str, document, schema: str, what: str) -> bool:
        if schema not in self._cache:
            spec = json.loads((self.folder / schema).read_text())
            self._cache[schema] = validators.validator_for(spec)(spec)
        errors = sorted(self._cache[schema].iter_errors(document), key=lambda e: list(e.path))
        for e in errors[:5]:
            at = "/".join(str(p) for p in e.path) or "top level"
            problems.error(where, f"{what} is not valid ({at}): {e.message}")
        return not errors


def validate(repo: Repo) -> Problems:
    problems = Problems()
    schemas = Schemas(repo.schemas)
    root = repo.hub_root

    def where(p):
        return rel(p, root)

    schemas.check(problems, where(repo.gov_dir / "hub.yml"), repo.hub, "hub.schema.json", "The hub settings")
    schemas.check(problems, where(repo.gov_dir / "classification.yaml"),
                  load_yaml(repo.gov_dir / "classification.yaml"), "classification.schema.json", "The classification")
    for g in sorted((repo.gov_dir / "glossary").glob("*.yaml")):
        doc = load_yaml(g)
        if schemas.check(problems, where(g), doc, "glossary.schema.json", "The glossary") and doc["domain"] != g.stem:
            problems.error(where(g), f"declares domain {doc['domain']} but is named after {g.stem}.")
    common_path = root / repo.hub["common_semantic_model"]["path"]
    schemas.check(problems, where(common_path), load_yaml(common_path), "ossie/osi-schema-0.1.1.json",
                  "The common semantic model")

    hub_version = repo.hub["common_semantic_model"]["version"]
    for d in repo.domains:
        gov_file = d.path / "governance.yml"
        if not gov_file.exists():
            problems.error(where(d.path), f"Domain {d.path.name} does not declare its target level (no governance.yml).")
            continue
        if schemas.check(problems, where(gov_file), d.gov, "governance.schema.json", "The governance declaration"):
            if d.gov["domain"] != d.path.name and d.path.name != f"data-dbt-{d.gov['domain']}":
                problems.error(where(gov_file), f"declares domain {d.gov['domain']} but its folder is {d.path.name}.")
            if d.gov["common_semantic_model_version"] != hub_version:
                problems.warn(where(gov_file), f"Domain {d.name} uses version {d.gov['common_semantic_model_version']} "
                                               f"of the common semantic model; the hub is at {hub_version}.")
        if not (repo.gov_dir / "glossary" / f"{d.name}.yaml").exists():
            problems.warn(where(d.path), f"Domain {d.name} has no glossary in governance/glossary/{d.name}.yaml.")
        for p in d.products:
            card_file = p.path / CARD
            if p.card is None:
                problems.error(where(p.path), f"{p.id} has no product card ({CARD}).")
                continue
            ok = schemas.check(problems, where(card_file), p.card, "bitol/odps-json-schema-v1.1.0.json",
                               f"The card of {p.id} (ODPS)")
            ok = schemas.check(problems, where(card_file), p.card, "data-product.profile.schema.json",
                               f"The card of {p.id}") and ok
            if ok:
                level = p.card_property("classification")
                if level not in repo.levels:
                    problems.error(where(card_file), f"The classification of {p.id} is {level!r}, "
                                                     f"which is not a level of governance/classification.yaml.")
                if p.card["domain"] != d.name:
                    problems.error(where(card_file), f"The card of {p.id} declares domain {p.card['domain']}.")
            for iface in p.interfaces:
                validate_contract(repo, problems, schemas, d, p, iface, where)
            if p.extension is not None:
                schemas.check(problems, where(p.path / f"{p.id}.ossie.yaml"), p.extension,
                              "semantic-extension.schema.json", f"The semantic extension of {p.id}")
    return problems


def validate_contract(repo, problems, schemas, d, p, iface, where):
    path = iface.contract_path
    if iface.contract is None:
        problems.warn(where(iface.sql), f"Interface {iface.name} v{iface.version} has no contract "
                                        f"({path.name}). Required at level 3 (GOV-301).")
        return
    if not schemas.check(problems, where(path), iface.contract, "bitol/odcs-json-schema-v3.2.0.json",
                         f"The contract of {iface.name}"):
        return
    c = iface.contract
    major = str(c.get("version", "")).split(".")[0]
    if major != str(iface.version):
        problems.error(where(path), f"The versions of {iface.name} and its contract do not match "
                                    f"(model v{iface.version}, contract {c.get('version')}).")
    worst = 0
    for obj in c.get("schema") or []:
        for prop in obj.get("properties") or []:
            level = prop.get("classification")
            if level is None:
                continue
            if level not in repo.levels:
                problems.error(where(path), f"Column {prop.get('name')} of {iface.name} is classified {level!r}, "
                                            f"which is not a level of governance/classification.yaml.")
            worst = max(worst, repo.ranks.get(level, 0))
    product_level = p.card_property("classification") if p.card else None
    if product_level in repo.ranks and worst > repo.ranks[product_level]:
        problems.warn(where(path), f"{iface.name} has columns more sensitive than its product "
                                   f"({p.id} is classified {product_level}).")
    if p.card:
        card_team = {(m.get("role"), m.get("username")) for m in p.card["team"].get("members", [])}
        team = c.get("team") if isinstance(c.get("team"), dict) else {}
        contract_team = {(m.get("role"), m.get("username")) for m in team.get("members", []) or []}
        if team.get("name") != p.tech_owner or not card_team <= contract_team:
            problems.error(where(path), f"The owners in the contract of {iface.name} differ from the product card "
                                        f"of {p.id}. Copy team.name and team.members from the card.")


# ---------------------------------------------------------------- semantic assembly

class AssemblyError(Exception):
    pass


def expression_sql(expr) -> str:
    if isinstance(expr, str):
        return expr
    for d in (expr or {}).get("dialects", []):
        if d.get("dialect") == "ANSI_SQL":
            return d["expression"]
    return (expr or {}).get("dialects", [{}])[0].get("expression", "")


def to_ossie_expression(expr) -> dict:
    return expr if isinstance(expr, dict) else {"dialects": [{"dialect": "ANSI_SQL", "expression": expr}]}


def sql_literal(value) -> str:
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def filter_sql(f) -> str:
    if "equals" in f:
        return f"{f['field']} = {sql_literal(f['equals'])}"
    return f"{f['field']} IN ({', '.join(sql_literal(v) for v in f['in'])})"


def datasets_used(sql: str, names: set[str]) -> set[str]:
    return {m.group(1) for m in QUALIFIED.finditer(sql) if m.group(1) in names}


@dataclass
class Assembly:
    """The common model plus one product's extension."""
    product: Product
    domain: Domain
    full: dict             # everything, private included: source of the dbt semantic configuration
    published: dict        # plain Ossie, without private semantics: what other domains and tools read
    private: set[str]      # names of private datasets, relationships and metrics


def assemble_product(repo: Repo, d: Domain, p: Product) -> Assembly:
    common_doc = repo.common_model()
    common = common_doc["semantic_model"][0]
    ext = p.extension or {}
    where = f"{p.id}.ossie.yaml"
    if ext.get("extends") != common["name"]:
        raise AssemblyError(f"{where}: extends {ext.get('extends')!r}, but the common model is {common['name']!r}.")

    common_datasets = {ds["name"] for ds in common.get("datasets", [])}
    common_metrics = {m["name"]: m for m in common.get("metrics", [])}
    private: set[str] = set()

    datasets = [dict(ds) for ds in common.get("datasets", [])]
    for ds in ext.get("datasets", []) or []:
        if ds["name"] in common_datasets:
            raise AssemblyError(f"{p.id} redefines {ds['name']}, which already has a common definition (GOV-316).")
        parts = ds["source"].split(".")
        is_interface = len(parts) == 3
        if not is_interface and not ds.get("private"):
            raise AssemblyError(f"Dataset {ds['name']} is shared but built on internal data that may change "
                                f"without notice. Mark it private or use a public interface (GOV-315).")
        if not is_interface and parts[0] != d.name:
            raise AssemblyError(f"Dataset {ds['name']} reads an internal model of {parts[0]}, "
                                f"which may change without notice (GOV-315).")
        out = {k: v for k, v in ds.items() if k != "private"}
        out["fields"] = [{**f, "expression": to_ossie_expression(f["expression"])} for f in ds.get("fields", [])]
        datasets.append(out)
        if ds.get("private"):
            private.add(ds["name"])
    names = {ds["name"] for ds in datasets}
    fields = {(ds["name"], f["name"]): f for ds in datasets for f in ds.get("fields", [])}

    relationships = [dict(r) for r in common.get("relationships", []) or []]
    for r in ext.get("relationships", []) or []:
        for side in (r["from"], r["to"]):
            if side not in names:
                raise AssemblyError(f"Relationship {r['name']} uses {side}, which is not a dataset of the model.")
        touches_private = r["from"] in private or r["to"] in private
        if touches_private and not r.get("private"):
            raise AssemblyError(f"Relationship {r['name']} is shared but uses a private dataset (GOV-315).")
        relationships.append({k: v for k, v in r.items() if k != "private"})
        if r.get("private"):
            private.add(r["name"])

    metrics = [dict(m) for m in common.get("metrics", [])]
    for m in ext.get("metrics", []) or []:
        name = m["name"]
        if name in common_metrics:
            raise AssemblyError(f"{p.id} redefines {name}, which already has a common definition (GOV-316).")
        if "derived_from" in m:
            parent = common_metrics.get(m["derived_from"])
            if parent is None:
                raise AssemblyError(f"{name} derives from {m['derived_from']}, which is not a common metric (GOV-317).")
            if not name.startswith(parent["name"] + "_"):
                raise AssemblyError(f"The name of {name} does not show which common metric it comes from: "
                                    f"it must start with {parent['name']}_ (GOV-318).")
            parent_sql = expression_sql(parent["expression"])
            if not AGGREGATE.match(parent_sql):
                raise AssemblyError(f"{name}: the standard's assembly only derives from a single aggregate "
                                    f"(SUM, AVG, MIN, MAX, COUNT); {parent['name']} is {parent_sql}.")
            for f in m["filters"]:
                ds_name, field_name = f["field"].split(".")
                target = fields.get((ds_name, field_name))
                if target is None or "dimension" not in target:
                    raise AssemblyError(f"{name} filters on {f['field']}, which is not a dimension of the model (GOV-317).")
                if ds_name in private and not m.get("private"):
                    raise AssemblyError(f"Metric {name} is shared but built on internal data (GOV-315).")
            condition = " AND ".join(filter_sql(f) for f in m["filters"])
            out = {
                "name": name,
                "expression": {"dialects": [{"dialect": "ANSI_SQL", "expression": f"{parent_sql} FILTER (WHERE {condition})"}]},
                "description": m.get("description", parent.get("description", "")),
                "custom_extensions": [{"vendor_name": "COMMON", "data": json.dumps(
                    {"dgac": {"derived_from": parent["name"], "filters": m["filters"]}}, ensure_ascii=False)}],
            }
        else:
            sql = expression_sql(m["expression"])
            used = datasets_used(sql, names)
            if not used:
                raise AssemblyError(f"Metric {name} does not name any dataset of the model (write dataset.field).")
            if used & private and not m.get("private"):
                raise AssemblyError(f"Metric {name} is shared but built on internal data that may change "
                                    f"without notice (GOV-315).")
            out = {"name": name, "expression": to_ossie_expression(m["expression"])}
            if m.get("description"):
                out["description"] = m["description"]
        if m.get("ai_context"):
            out["ai_context"] = m["ai_context"]
        metrics.append(out)
        if m.get("private"):
            private.add(name)

    version = repo.hub["common_semantic_model"]["version"]
    meta = {"vendor_name": "COMMON", "data": json.dumps({"dgac": {
        "standard_version": repo.hub["standard_version"], "common_model": common["name"],
        "common_model_version": d.gov.get("common_semantic_model_version", version),
        "product": f"{d.name}.{p.id}"}})}
    model = {"name": f"{d.name}_{p.id}",
             "description": f"Common model {common['name']} extended by the {p.id} data product of {d.name}.",
             "datasets": datasets, "relationships": relationships, "metrics": metrics,
             "custom_extensions": [meta]}
    full = {"version": common_doc["version"], "semantic_model": [model]}
    published_model = dict(model)
    published_model["datasets"] = [x for x in datasets if x["name"] not in private]
    published_model["relationships"] = [x for x in relationships if x["name"] not in private]
    published_model["metrics"] = [x for x in metrics if x["name"] not in private]
    published = {"version": common_doc["version"], "semantic_model": [published_model]}
    return Assembly(p, d, full, published, private)


def physical_name(repo: Repo, source: str) -> str | None:
    """`domain.interface.v1` or `domain.model` → database.schema.table, from the dbt manifests on disk."""
    parts = source.split(".")
    dom = repo.domain(parts[0])
    manifest = repo.dbt_manifest(dom) if dom else None
    if not manifest:
        return None
    key = f"model.{parts[0]}.{parts[1]}" + (f".{parts[2]}" if len(parts) == 3 else "")
    node = manifest.get("nodes", {}).get(key)
    if not node:
        return None
    return ".".join(x for x in (node.get("database"), node.get("schema"), node.get("alias")) if x)


def published_with_physical_sources(repo: Repo, a: Assembly) -> dict:
    doc = json.loads(json.dumps(a.published))
    for ds in doc["semantic_model"][0]["datasets"]:
        physical = physical_name(repo, ds["source"])
        if physical:
            ds.setdefault("custom_extensions", []).append(
                {"vendor_name": "COMMON", "data": json.dumps({"dgac": {"interface": ds["source"]}})})
            ds["source"] = physical
    return doc


# ---------------------------------------------------------------- dbt semantic configuration

def dbt_ref(d: Domain, source: str) -> str | None:
    parts = source.split(".")
    version = parts[2][1:] if len(parts) == 3 else None
    if parts[0] == d.name:
        return f"ref('{parts[1]}', v={version})" if version else f"ref('{parts[1]}')"
    for e in d.externals:
        if e.domain == parts[0] and e.interface == parts[1] and (version is None or str(e.version) == version):
            return f"ref('{e.model}')"
    return None


def dbt_semantic_config(a: Assembly) -> tuple[str, list[str]]:
    """MetricFlow semantic models and metrics for the product's dbt project, private semantics included."""
    model = a.full["semantic_model"][0]
    notes = []
    refs = {}
    for ds in model["datasets"]:
        ref = dbt_ref(a.domain, ds["source"])
        if ref:
            refs[ds["name"]] = ref
        else:
            notes.append(f"dataset {ds['name']} ({ds['source']}) is not read by {a.domain.name}: left out")

    measures: dict[str, list] = {name: [] for name in refs}
    measure_of = {}
    for m in model["metrics"]:
        derived = next((json.loads(x["data"])["dgac"] for x in m.get("custom_extensions", [])
                        if "derived_from" in json.loads(x["data"]).get("dgac", {})), None)
        if derived:
            continue
        match = AGGREGATE.match(expression_sql(m["expression"]))
        if not match:
            notes.append(f"metric {m['name']} is not a single aggregate: not translated to dbt")
            continue
        agg, distinct, ds_name, col = match.groups()
        if ds_name not in refs:
            continue
        field_def = next((f for f in next(x for x in model["datasets"] if x["name"] == ds_name).get("fields", [])
                          if f["name"] == col), None)
        expr = expression_sql(field_def["expression"]) if field_def else col
        mf_agg = "count_distinct" if distinct else MF_AGG[agg.upper()]
        measures[ds_name].append({"name": m["name"], "agg": mf_agg, "expr": expr})
        measure_of[m["name"]] = m["name"]

    semantic_models = []
    for ds in model["datasets"]:
        if ds["name"] not in refs:
            continue
        entities = []
        if ds.get("primary_key"):
            entities.append({"name": ds["name"], "type": "primary", "expr": ds["primary_key"][0]})
        for r in model.get("relationships", []) or []:
            if r["from"] == ds["name"] and r["to"] in refs:
                entities.append({"name": r["to"], "type": "foreign", "expr": r["from_columns"][0]})
        dims, time_dims = [], []
        for f in ds.get("fields", []):
            if "dimension" not in f:
                continue
            dim = {"name": f["name"]}
            expr = expression_sql(f["expression"])
            if expr != f["name"]:
                dim["expr"] = expr
            if f["dimension"].get("is_time"):
                dim.update({"type": "time", "type_params": {"time_granularity": "day"}})
                time_dims.append(f["name"])
            else:
                dim["type"] = "categorical"
            dims.append(dim)
        sm = {"name": ds["name"], "description": ds.get("description", ""), "model": refs[ds["name"]]}
        if measures[ds["name"]]:
            if not time_dims:
                notes.append(f"dataset {ds['name']} has metrics but no time dimension: dbt needs one")
                continue
            sm["defaults"] = {"agg_time_dimension": time_dims[0]}
        sm["entities"] = entities
        sm["dimensions"] = dims
        if measures[ds["name"]]:
            sm["measures"] = measures[ds["name"]]
        semantic_models.append(sm)

    metrics = []
    for m in model["metrics"]:
        derived = next((json.loads(x["data"])["dgac"] for x in m.get("custom_extensions", [])
                        if "derived_from" in json.loads(x["data"]).get("dgac", {})), None)
        if derived:
            measure = measure_of.get(derived["derived_from"])
            if not measure:
                continue
            conditions = []
            for f in derived["filters"]:
                ds_name, field_name = f["field"].split(".")
                dim = "{{ Dimension('" + f"{ds_name}__{field_name}" + "') }}"
                if "equals" in f:
                    conditions.append(f"{dim} = {sql_literal(f['equals'])}")
                else:
                    conditions.append(f"{dim} IN ({', '.join(sql_literal(v) for v in f['in'])})")
            metrics.append({"name": m["name"], "label": m["name"], "description": m.get("description", ""),
                            "type": "simple", "type_params": {"measure": measure},
                            "filter": " AND ".join(conditions)})
        elif m["name"] in measure_of:
            metrics.append({"name": m["name"], "label": m["name"], "description": m.get("description", ""),
                            "type": "simple", "type_params": {"measure": measure_of[m["name"]]}})

    header = [GENERATED,
              f"# dbt semantic configuration of {a.product.id}, from the common model and {a.product.id}.ossie.yaml.",
              "# Private metrics are included: the domain computes them; they are left out of the published model."]
    header += [f"# Note: {n}." for n in notes]
    body = dump_yaml({"semantic_models": semantic_models, "metrics": metrics})
    return "\n".join(header) + "\n" + body, notes


# ---------------------------------------------------------------- generate

def generated_files(repo: Repo) -> dict[Path, str]:
    files: dict[Path, str] = {}
    by_root: dict[Path, list[Domain]] = {}
    for d in repo.domains:
        by_root.setdefault(d.repo_root, []).append(d)
    for root, domains in by_root.items():
        files[root / ".github" / "CODEOWNERS"] = render_codeowners(repo, root, domains)
    for d in repo.domains:
        files[d.path / "selectors.yml"] = render_selectors(d)
        for p in d.products:
            if p.card:
                files[p.path / "_group.yml"] = render_group(p)
            if p.extension is not None:
                try:
                    text, _ = dbt_semantic_config(assemble_product(repo, d, p))
                    files[p.path / "_semantic.generated.yml"] = text
                except AssemblyError:
                    pass  # reported by `assemble`
    return files


def render_codeowners(repo: Repo, root: Path, domains: list[Domain]) -> str:
    central = repo.hub["central_team"]
    lines = [GENERATED.replace("#", "#", 1),
             "# Who must approve a pull request, per path (the last matching line wins).",
             "# Data Owner and committee approvals (GOV-A01 to A04) are collected outside GitHub in V1.", ""]
    monorepo = root == repo.hub_root
    if monorepo:
        lines += [f"*  {central}", f"/governance/  {central}", f"/schemas/  {central}", f"/tools/  {central}", ""]
    else:
        lines += [f"*  {domains[0].gov.get('team', central)}", ""]
    for d in sorted(domains, key=lambda x: x.name):
        prefix = "/" + rel(d.path, root) + "/" if d.path != root else "/"
        if monorepo:
            lines.append(f"{prefix}  {d.gov.get('team', central)}")
        for p in d.products:
            if p.tech_owner:
                lines.append(f"{prefix}dataproducts/{p.id}/  {p.tech_owner}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_group(p: Product) -> str:
    group = {"name": p.id,
             "owner": {"name": p.tech_owner, "email": p.member("data-owner")},
             "description": (p.card.get("description") or {}).get("purpose", ""),
             "config": {"meta": {"data_steward": p.member("data-steward"),
                                 "classification": p.card_property("classification"),
                                 "contains_pii": p.card_property("containsPii")}}}
    return f"{GENERATED}\n# The dbt group of {p.id}, from its product card {CARD} (source of truth for owners).\n" \
           + dump_yaml({"groups": [group]})


def render_selectors(d: Domain) -> str:
    selectors = [{"name": p.id, "description": f"Build and deploy {p.id} on its own (GOV-205).",
                  "definition": {"method": "group", "value": p.id}} for p in d.products]
    return f"{GENERATED}\n# One selector per data product: dbt build --selector <product>\n" \
           + dump_yaml({"selectors": selectors})


def generate(repo: Repo, check: bool) -> int:
    stale = []
    for path, text in generated_files(repo).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    for path in stale:
        print(f"{'stale' if check else 'wrote'}  {rel(path, repo.hub_root)}")
    if check and stale:
        print("error    Generated files are out of date: run `python tools/dgac.py generate` and commit.")
        return 1
    return 0


# ---------------------------------------------------------------- assemble and manifest

def assemble(repo: Repo) -> int:
    problems = Problems()
    schemas = Schemas(repo.schemas)
    for d in repo.domains:
        for p in d.products:
            if p.extension is None:
                continue
            try:
                a = assemble_product(repo, d, p)
            except AssemblyError as e:
                problems.error(rel(p.path, repo.hub_root), str(e))
                continue
            doc = published_with_physical_sources(repo, a)
            out = repo.build_dir(d) / "semantic" / d.name / f"{p.id}.assembled.ossie.yaml"
            if schemas.check(problems, rel(out, repo.hub_root), doc, "ossie/osi-schema-0.1.1.json",
                             f"The business definitions of {p.id}"):
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text("# yaml-language-server: $schema=https://raw.githubusercontent.com/apache/ossie/"
                               "osi-0.1.1-rc1/core-spec/osi-schema.json\n"
                               f"# Assembled by `dgac assemble`: common model + {p.id}.ossie.yaml, "
                               "private semantics left out. Do not edit.\n" + dump_yaml(doc), encoding="utf-8")
                print(f"wrote  {rel(out, repo.hub_root)}")
    return problems.report()


def contract_id(repo: Repo, domain: str, interface: str, version: int | None) -> str:
    d = repo.domain(domain)
    if d:
        for p in d.products:
            for i in p.interfaces:
                if i.name == interface and (version is None or i.version == version) and i.contract:
                    return str(i.contract.get("id"))
    return f"{domain}-{interface}-v{version}"


def product_manifest(repo: Repo, d: Domain, p: Product) -> dict:
    manifest_dbt = repo.dbt_manifest(d) or {}
    interfaces = []
    for i in p.interfaces:
        node = manifest_dbt.get("nodes", {}).get(f"model.{d.name}.{i.name}.v{i.version}")
        c = i.contract or {}
        sla = {s.get("property"): {"value": s.get("value"), "unit": s.get("unit")} for s in c.get("slaProperties", []) or []}
        columns = [{"name": x.get("name"), "type": x.get("logicalType"), "classification": x.get("classification"),
                    "description": x.get("description")}
                   for obj in c.get("schema", []) or [] for x in obj.get("properties", []) or []]
        interfaces.append({
            "name": i.name, "version": i.version,
            "ref": f"ref('{d.name}', '{i.name}', v={i.version})",
            "relation": ".".join(x for x in (node.get("database"), node.get("schema"), node.get("alias")) if x) if node else None,
            "contract": {"id": c.get("id"), "version": c.get("version"), "status": c.get("status"),
                         "path": rel(i.contract_path, d.repo_root), "sla": sla} if i.contract else None,
            "columns": columns,
        })
    reads = [{"domain": e.domain, "interface": e.interface, "version": e.version, "via": e.model,
              "contractId": contract_id(repo, e.domain, e.interface, e.version)}
             for e in d.externals if e.group == p.id]
    consumers = sorted({(other.name, e.group) for other in repo.domains for e in other.externals
                        if e.domain == d.name and any(i.name == e.interface for i in p.interfaces)})
    odps = dict(p.card or {})
    if reads:
        odps["inputPorts"] = [{"name": r["interface"], "version": str(r["version"]), "contractId": r["contractId"]}
                              for r in reads]
    if interfaces:
        odps["outputPorts"] = [{"name": i["name"], "version": str(i["version"]), "contractId": i["contract"]["id"]}
                               for i in interfaces if i["contract"]]
    semantic = None
    if p.extension is not None:
        try:
            a = assemble_product(repo, d, p)
            semantic = {"assembled": rel(repo.build_dir(d) / "semantic" / d.name / f"{p.id}.assembled.ossie.yaml", d.repo_root),
                        "shared_metrics": [m["name"] for m in a.published["semantic_model"][0]["metrics"]],
                        "private_metrics": sorted(n for n in a.private if n in {m["name"] for m in a.full["semantic_model"][0]["metrics"]})}
        except AssemblyError as e:
            semantic = {"error": str(e)}
    return {
        "id": p.id, "name": (p.card or {}).get("name"), "status": (p.card or {}).get("status"),
        "description": ((p.card or {}).get("description") or {}).get("purpose"),
        "owners": {"data_owner": p.member("data-owner"), "data_steward": p.member("data-steward"),
                   "tech_owner": p.tech_owner},
        "classification": p.card_property("classification"), "contains_pii": p.card_property("containsPii"),
        "glossary_terms": [x.get("url") for x in (p.card or {}).get("authoritativeDefinitions", []) or []],
        "interfaces": interfaces, "reads_from": reads,
        "consumers": [{"domain": dom, "product": prod} for dom, prod in consumers],
        "semantic": semantic, "odps": odps,
    }


def manifest(repo: Repo) -> int:
    for d in repo.domains:
        doc = {
            "standard": "data-governance-as-code", "standard_version": d.gov.get("standard_version"),
            "generated_at": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat(),
            "organisation": repo.hub.get("organisation"),
            "domain": {"name": d.name, "team": d.gov.get("team"), "target_level": d.gov.get("target_level"),
                       "common_semantic_model_version": d.gov.get("common_semantic_model_version"),
                       "ossie_version": d.gov.get("ossie_version")},
            "products": [product_manifest(repo, d, p) for p in d.products],
            "dbt": {"manifest": rel(d.path / "target" / "manifest.json", d.repo_root)
                    if repo.dbt_manifest(d) else None},
        }
        out = repo.build_dir(d) / d.name / "governance-manifest.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote  {rel(out, repo.hub_root)}")
    return 0


# ---------------------------------------------------------------- build

def build(repo: Repo, dbt: str) -> int:
    for d in repo.order():
        repo.build_dir(d).mkdir(parents=True, exist_ok=True)   # where the example's DuckDB file lives
        for p in d.products:
            print(f"== {d.name}: dbt build --selector {p.id}", flush=True)
            code = subprocess.call([dbt, "build", "--selector", p.id], cwd=d.path)
            if code:
                return code
        if not d.products:
            subprocess.call([dbt, "parse"], cwd=d.path)
    return 0



# ---------------------------------------------------------------- main

def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="dgac", description="Data Governance as Code: the standard's tool.")
    parser.add_argument("--hub", type=Path, default=TOOL_ROOT, help="folder holding governance/ (default: this repository)")
    parser.add_argument("--domain", type=Path, action="append", dest="domains",
                        help="a domain folder (default: every domains/*/ of the hub)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate", help="check every governance file against its schema")
    g = sub.add_parser("generate", help="rewrite CODEOWNERS, dbt groups, selectors and dbt semantic config")
    g.add_argument("--check", action="store_true", help="fail if a generated file is out of date (CI)")
    b = sub.add_parser("build", help="run dbt for every domain, producers first, one product at a time")
    b.add_argument("--dbt", default=str(Path(sys.executable).parent / "dbt"))
    sub.add_parser("assemble", help="write each product's assembled Ossie model to build/semantic/")
    sub.add_parser("manifest", help="write build/<domain>/governance-manifest.json")
    nd = sub.add_parser("new-domain", help="create a domain folder, or a domain repository with --repo")
    nd.add_argument("domain")
    nd.add_argument("--team", required=True, help="GitHub team of the domain, e.g. @org/sales-data")
    nd.add_argument("--repo", type=Path, help="create data-dbt-<domain>/ in this folder instead of domains/")
    np_ = sub.add_parser("new-product", help="create a data product folder, card and dbt group")
    np_.add_argument("domain")
    np_.add_argument("product")
    np_.add_argument("--team", required=True, help="tech owner: GitHub team, e.g. @org/sales-data")
    np_.add_argument("--owner", required=True, help="Data Owner's work email")
    np_.add_argument("--steward", required=True, help="Data Steward's work email")
    np_.add_argument("--name", help="readable name (default: from the id)")
    ni = sub.add_parser("new-interface", help="create a public interface, version 1, with its contract")
    ni.add_argument("domain")
    ni.add_argument("product")
    ni.add_argument("interface")
    args = parser.parse_args(argv)

    repo = Repo(args.hub.resolve(), [p.resolve() for p in args.domains] if args.domains else None)
    if args.command == "validate":
        problems = validate(repo)
        code = problems.report()
        if not code:
            print(f"ok       {len(repo.domains)} domains, {sum(len(d.products) for d in repo.domains)} data products.")
        return code
    if args.command == "generate":
        return generate(repo, args.check)
    if args.command == "build":
        return build(repo, args.dbt)
    if args.command == "assemble":
        return assemble(repo)
    if args.command == "manifest":
        return manifest(repo)
    if args.command == "new-domain":
        return new_domain(repo, args.domain, args.team, args.repo.resolve() if args.repo else None)
    if args.command == "new-product":
        return new_product(repo, args.domain, args.product, args.team, args.owner, args.steward, args.name)
    if args.command == "new-interface":
        return new_interface(repo, args.domain, args.product, args.interface)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
